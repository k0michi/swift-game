    public static let extendedMask: UInt32 = 1 << 29
    public static let scancodeMask: UInt32 = 1 << 30

    public var isScancode: Bool {
        return (rawValue & Self.scancodeMask) != 0
    }

    public var isExtended: Bool {
        return (rawValue & Self.extendedMask) != 0
    }

    public var scancode: Scancode? {
        guard isScancode else { return nil }
        return Scancode(rawValue: UInt32(rawValue & ~Self.scancodeMask))
