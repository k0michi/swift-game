#!/usr/bin/env swift

// Writes Sources/VectorMath/Generated: the vector and matrix types of every
// size, their operators and the WGSL built-in functions on them. Run it with
// `swift scripts/generate-vector-math.swift` after changing it, and commit
// what it writes. CI fails when the committed sources differ from its output.

import Foundation

let sizes = [2, 3, 4]
let componentNames = ["x", "y", "z", "w"]
let colorNames = ["r", "g", "b", "a"]

func vector(_ size: Int, _ scalar: String = "Scalar") -> String {
    "Vector\(size)<\(scalar)>"
}

func matrix(_ columns: Int, _ rows: Int, _ scalar: String = "Scalar") -> String {
    "Matrix\(columns)x\(rows)<\(scalar)>"
}

/// `body` applied to each of the first `size` component names, joined.
func each(_ size: Int, separator: String = ", ", _ body: (String) -> String) -> String {
    componentNames.prefix(size).map(body).joined(separator: separator)
}

/// `body` applied to each of `0..<count`, joined.
func each(count: Int, separator: String = ", ", _ body: (Int) -> String) -> String {
    (0..<count).map(body).joined(separator: separator)
}

/// The ways to write `size` as an ordered sum of parts, other than all ones
/// and `size` itself: the vectors and scalars WGSL builds a vector from.
func compositions(of size: Int) -> [[Int]] {
    func all(_ remaining: Int) -> [[Int]] {
        guard remaining > 0 else { return [[]] }
        return (1...remaining).flatMap { first in all(remaining - first).map { [first] + $0 } }
    }
    return all(size).filter { $0.count > 1 && $0.contains { $0 > 1 } }
}

/// Every sequence of `length` elements drawn from `elements`, in order.
func sequences(of elements: [String], length: Int) -> [[String]] {
    guard length > 0 else { return [[]] }
    return elements.flatMap { first in
        sequences(of: elements, length: length - 1).map { [first] + $0 }
    }
}

final class Source {
    private(set) var text =
        "// This file is generated by scripts/generate-vector-math.swift. Do not edit it by hand.\n"
    private var indentation = 0
    // Blank lines separate declarations, but not a block's first from its brace.
    private var isAtBlockStart = false

    func line(_ content: String = "") {
        for line in content.split(separator: "\n", omittingEmptySubsequences: false) {
            if line.isEmpty {
                if !isAtBlockStart {
                    text += "\n"
                }
            } else {
                text += String(repeating: "    ", count: indentation) + line + "\n"
                isAtBlockStart = line.hasSuffix("{")
            }
        }
    }

    /// A switch statement, whose cases Swift style keeps at its own indentation.
    func switchBlock(_ subject: String, _ body: () -> Void) {
        line("switch \(subject) {")
        body()
        line("}")
    }

    func block(_ opening: String, _ body: () -> Void) {
        line(opening + " {")
        indentation += 1
        body()
        indentation -= 1
        line("}")
    }

    /// An inlinable declaration whose body is `statements`.
    func inlinable(_ declaration: String, _ statements: String...) {
        line()
        line("@inlinable")
        block(declaration) {
            for statement in statements {
                line(statement)
            }
        }
    }
}

// MARK: - Vectors

/// Operators that apply `expression` to each pair of components, between two
/// vectors and between a vector and a scalar on either side.
func componentwiseOperators(
    _ source: Source, size: Int, _ operation: String,
    _ expression: @escaping (String, String) -> String
) {
    let forms = [
        ("lhs: Self, rhs: Self", { (c: String) in expression("lhs.\(c)", "rhs.\(c)") }),
        ("lhs: Self, rhs: Scalar", { (c: String) in expression("lhs.\(c)", "rhs") }),
        ("lhs: Scalar, rhs: Self", { (c: String) in expression("lhs", "rhs.\(c)") }),
    ]
    for (parameters, component) in forms {
        source.inlinable(
            "public static func \(operation) (\(parameters)) -> Self",
            "Self(\(each(size, component)))")
    }
    for rhs in ["Self", "Scalar"] {
        source.inlinable(
            "public static func \(operation)= (lhs: inout Self, rhs: \(rhs))",
            "lhs = lhs \(operation) rhs")
    }
}

func generateVector(_ size: Int) -> String {
    let source = Source()
    let name = "Vector\(size)"

    source.line()
    source.line("import RealModule")

    source.line()
    source.line(
        "/// A vector of \(size) scalars, stored as \(each(size) { $0 }) in that order with no padding.")
    source.line("///")
    source.line("/// Its operators and the free functions on it follow WGSL's `vec\(size)<T>`.")
    source.line("@frozen")
    source.block("public struct \(name)<Scalar>") {
        for component in componentNames.prefix(size) {
            source.line("public var \(component): Scalar")
        }
        source.inlinable(
            "public init(\(each(size) { "\($0): Scalar" }))",
            each(size, separator: "\n") { "self.\($0) = \($0)" })
        source.inlinable(
            "public init(\(each(size) { "_ \($0): Scalar" }))",
            "self.init(\(each(size) { "\($0): \($0)" }))")
        source.line()
        source.line("/// A vector with every component set to `value`.")
        source.line("@inlinable")
        source.block("public init(repeating value: Scalar)") {
            source.line("self.init(\(each(size) { _ in "value" }))")
        }

        for parts in compositions(of: size) {
            var parameters: [String] = []
            var arguments: [String] = []
            var start = 0
            for part in parts {
                let names = componentNames[start..<(start + part)].joined()
                if part == 1 {
                    parameters.append("_ \(names): Scalar")
                    arguments.append(names)
                } else {
                    parameters.append("_ \(names): \(vector(part))")
                    arguments.append(each(part) { "\(names).\($0)" })
                }
                start += part
            }
            source.line()
            source.line("/// The components of the arguments, in order.")
            source.line("@inlinable")
            source.block("public init(\(parameters.joined(separator: ", ")))") {
                source.line("self.init(\(arguments.joined(separator: ", ")))")
            }
        }

        source.line()
        source.line("/// The number of components.")
        source.line("@inlinable")
        source.line("public static var scalarCount: Int { \(size) }")

        source.line()
        source.line("/// The component at `index`, counting \(each(size) { $0 }) from 0.")
        source.line("@inlinable")
        source.block("public subscript(index: Int) -> Scalar") {
            source.block("get") {
                source.switchBlock("index") {
                    for (index, component) in componentNames.prefix(size).enumerated() {
                        source.line("case \(index): return \(component)")
                    }
                    source.line("default: preconditionFailure(\"Index out of range\")")
                }
            }
            source.block("set") {
                source.switchBlock("index") {
                    for (index, component) in componentNames.prefix(size).enumerated() {
                        source.line("case \(index): \(component) = newValue")
                    }
                    source.line("default: preconditionFailure(\"Index out of range\")")
                }
            }
        }
    }

    // Conformances.
    source.line()
    source.line("extension \(name): Sendable where Scalar: Sendable {}")
    source.line()
    source.block("extension \(name): Equatable where Scalar: Equatable") {
        source.line("/// Whether every component is equal, for conditions and `Equatable`.")
        source.line("///")
        source.line("/// Where either fits, as in `let equal = a == b`, the `==` that compares")
        source.line("/// each component and returns a `\(vector(size, "Bool"))` is chosen, as in WGSL.")
        source.line("@inlinable")
        source.line("@_disfavoredOverload")
        source.block("public static func == (lhs: Self, rhs: Self) -> Bool") {
            source.line(each(size, separator: " && ") { "lhs.\($0) == rhs.\($0)" })
        }
    }
    source.line()
    source.block("extension \(name): Hashable where Scalar: Hashable") {
        source.line("@inlinable")
        source.block("public func hash(into hasher: inout Hasher)") {
            for component in componentNames.prefix(size) {
                source.line("hasher.combine(\(component))")
            }
        }
    }
    source.line()
    source.line("/// Encoded as an array of its components.")
    source.block("extension \(name): Encodable where Scalar: Encodable") {
        source.line("@inlinable")
        source.block("public func encode(to encoder: any Encoder) throws") {
            source.line("var container = encoder.unkeyedContainer()")
            for component in componentNames.prefix(size) {
                source.line("try container.encode(\(component))")
            }
        }
    }
    source.line()
    source.block("extension \(name): Decodable where Scalar: Decodable") {
        source.line("@inlinable")
        source.block("public init(from decoder: any Decoder) throws") {
            source.line("var container = try decoder.unkeyedContainer()")
            for component in componentNames.prefix(size) {
                source.line("let \(component) = try container.decode(Scalar.self)")
            }
            source.line("self.init(\(each(size) { $0 }))")
        }
    }
    source.line()
    source.block("extension \(name): CustomStringConvertible") {
        source.block("public var description: String") {
            source.line("\"\(name)(\(each(size) { "\\(\($0))" }))\"")
        }
    }

    // Conversions.
    let conversions = [
        ("BinaryInteger", "BinaryInteger", "Converts each component, trapping if it does not fit."),
        (
            "BinaryInteger", "BinaryFloatingPoint",
            "Converts each component, rounding toward zero and trapping if it does not fit."
        ),
        ("BinaryFloatingPoint", "BinaryInteger", "Converts each component, rounding to the nearest value."),
        ("BinaryFloatingPoint", "BinaryFloatingPoint", "Converts each component, rounding to the nearest value."),
    ]
    for (scalar, other, documentation) in conversions {
        source.line()
        source.block("extension \(name) where Scalar: \(scalar)") {
            source.line("/// \(documentation)")
            source.line("@inlinable")
            source.block("public init<Other: \(other)>(_ other: \(vector(size, "Other")))") {
                source.line("self.init(\(each(size) { "Scalar(other.\($0))" }))")
            }
        }
    }

    // Arithmetic.
    source.line()
    source.block("extension \(name): AdditiveArithmetic where Scalar: AdditiveArithmetic") {
        source.line("@inlinable")
        source.line("public static var zero: Self { Self(repeating: .zero) }")
        for operation in ["+", "-"] {
            source.inlinable(
                "public static func \(operation) (lhs: Self, rhs: Self) -> Self",
                "Self(\(each(size) { "lhs.\($0) \(operation) rhs.\($0)" }))")
        }
    }
    source.line()
    source.block("extension \(name) where Scalar: AdditiveArithmetic") {
        for operation in ["+", "-"] {
            for parameters in ["lhs: Self, rhs: Scalar", "lhs: Scalar, rhs: Self"] {
                let lhs = parameters.hasPrefix("lhs: Self") ? { (c: String) in "lhs.\(c)" } : { _ in "lhs" }
                let rhs = parameters.hasSuffix("rhs: Self") ? { (c: String) in "rhs.\(c)" } : { _ in "rhs" }
                source.inlinable(
                    "public static func \(operation) (\(parameters)) -> Self",
                    "Self(\(each(size) { "\(lhs($0)) \(operation) \(rhs($0))" }))")
            }
            for rhs in ["Self", "Scalar"] {
                source.inlinable(
                    "public static func \(operation)= (lhs: inout Self, rhs: \(rhs))",
                    "lhs = lhs \(operation) rhs")
            }
        }
    }
    source.line()
    source.line("// Products are taken component by component, as in WGSL.")
    source.block("extension \(name) where Scalar: Numeric") {
        componentwiseOperators(source, size: size, "*") { "\($0) * \($1)" }
    }
    source.line()
    source.block("extension \(name) where Scalar: SignedNumeric") {
        source.inlinable(
            "public static prefix func - (operand: Self) -> Self",
            "Self(\(each(size) { "-operand.\($0)" }))")
    }
    source.line()
    source.line("// `%` is the remainder of division truncated toward zero, as in WGSL.")
    source.block("extension \(name) where Scalar: FloatingPoint") {
        componentwiseOperators(source, size: size, "/") { "\($0) / \($1)" }
        componentwiseOperators(source, size: size, "%") { "\($0).truncatingRemainder(dividingBy: \($1))" }
    }
    source.line()
    source.block("extension \(name) where Scalar: BinaryInteger") {
        for operation in ["/", "%", "&", "|", "^", "<<", ">>"] {
            componentwiseOperators(source, size: size, operation) { "\($0) \(operation) \($1)" }
        }
        source.inlinable(
            "public static prefix func ~ (operand: Self) -> Self",
            "Self(\(each(size) { "~operand.\($0)" }))")
    }
    source.line()
    source.line("// Arithmetic that wraps around on overflow instead of trapping.")
    source.block("extension \(name) where Scalar: FixedWidthInteger") {
        for operation in ["&+", "&-", "&*"] {
            componentwiseOperators(source, size: size, operation) { "\($0) \(operation) \($1)" }
        }
    }

    // Comparisons.
    source.line()
    source.line("// Comparisons take each pair of components and return whether each holds,")
    source.line("// as in WGSL. `all` and `any` reduce the result to a `Bool`.")
    source.block("extension \(name) where Scalar: Equatable") {
        for operation in ["==", "!="] {
            source.inlinable(
                "public static func \(operation) (lhs: Self, rhs: Self) -> \(vector(size, "Bool"))",
                "\(vector(size, "Bool"))(\(each(size) { "lhs.\($0) \(operation) rhs.\($0)" }))")
        }
    }
    source.line()
    source.block("extension \(name) where Scalar: Comparable") {
        for operation in ["<", "<=", ">", ">="] {
            source.inlinable(
                "public static func \(operation) (lhs: Self, rhs: Self) -> \(vector(size, "Bool"))",
                "\(vector(size, "Bool"))(\(each(size) { "lhs.\($0) \(operation) rhs.\($0)" }))")
        }
    }
    source.line()
    source.block("extension \(name) where Scalar == Bool") {
        for (operation, logical) in [("&", "&&"), ("|", "||")] {
            source.inlinable(
                "public static func \(operation) (lhs: Self, rhs: Self) -> Self",
                "Self(\(each(size) { "lhs.\($0) \(logical) rhs.\($0)" }))")
            source.inlinable(
                "public static func \(operation)= (lhs: inout Self, rhs: Self)",
                "lhs = lhs \(operation) rhs")
        }
        source.inlinable(
            "public static prefix func ! (operand: Self) -> Self",
            "Self(\(each(size) { "!operand.\($0)" }))")
    }

    generateVectorFunctions(source, size: size)
    return source.text
}

/// The WGSL built-in functions on `Vector<size>`.
func generateVectorFunctions(_ source: Source, size: Int) {
    let type = vector(size)
    let bools = vector(size, "Bool")
    let construct = "Vector\(size)"

    source.line()
    source.line("// MARK: - Logical built-in functions")
    source.line()
    source.line("/// Whether every component is true.")
    source.line("@inlinable")
    source.block("public func all(_ e: \(bools)) -> Bool") {
        source.line(each(size, separator: " && ") { "e.\($0)" })
    }
    source.line()
    source.line("/// Whether any component is true.")
    source.line("@inlinable")
    source.block("public func any(_ e: \(bools)) -> Bool") {
        source.line(each(size, separator: " || ") { "e.\($0)" })
    }
    source.line()
    source.line("/// Each component of `t` where `condition` is true, and of `f` where it is false.")
    source.line("@inlinable")
    source.block("public func select<Scalar>(_ f: \(type), _ t: \(type), _ condition: \(bools)) -> \(type)") {
        source.line("\(construct)(\(each(size) { "condition.\($0) ? t.\($0) : f.\($0)" }))")
    }

    source.line()
    source.line("// MARK: - Numeric built-in functions")

    // Functions applied to each component: name, constraint, parameters and
    // the expression for one component.
    typealias Componentwise = (
        name: String, constraint: String, parameters: [String], documentation: String,
        expression: (String) -> String
    )
    let componentwise: [Componentwise] = [
        ("abs", "SignedNumeric & Comparable", ["e"], "The absolute value of each component.", { "Swift.abs(e.\($0))" }),
        ("sign", "SignedNumeric & Comparable", ["e"], "The sign of each component: -1, 0 or 1.", { "sign(e.\($0))" }),
        ("min", "Comparable", ["e1", "e2"], "The smaller of each pair of components.", { "Swift.min(e1.\($0), e2.\($0))" }),
        ("max", "Comparable", ["e1", "e2"], "The larger of each pair of components.", { "Swift.max(e1.\($0), e2.\($0))" }),
        (
            "clamp", "Comparable", ["e", "low", "high"], "Each component of `e`, limited to the range from `low` to `high`.",
            { "clamp(e.\($0), low.\($0), high.\($0))" }
        ),
        ("floor", "FloatingPoint", ["e"], "Each component rounded down.", { "e.\($0).rounded(.down)" }),
        ("ceil", "FloatingPoint", ["e"], "Each component rounded up.", { "e.\($0).rounded(.up)" }),
        (
            "round", "FloatingPoint", ["e"], "Each component rounded to the nearest integer, ties to even.",
            { "e.\($0).rounded(.toNearestOrEven)" }
        ),
        ("trunc", "FloatingPoint", ["e"], "Each component rounded toward zero.", { "e.\($0).rounded(.towardZero)" }),
        ("fract", "FloatingPoint", ["e"], "The fractional part of each component, `e - floor(e)`.", { "fract(e.\($0))" }),
        ("sqrt", "FloatingPoint", ["e"], "The square root of each component.", { "e.\($0).squareRoot()" }),
        ("inverseSqrt", "FloatingPoint", ["e"], "The reciprocal of the square root of each component.", { "inverseSqrt(e.\($0))" }),
        ("saturate", "FloatingPoint", ["e"], "Each component limited to the range from 0 to 1.", { "saturate(e.\($0))" }),
        ("degrees", "FloatingPoint", ["e"], "Each component converted from radians to degrees.", { "degrees(e.\($0))" }),
        ("radians", "FloatingPoint", ["e"], "Each component converted from degrees to radians.", { "radians(e.\($0))" }),
        (
            "step", "FloatingPoint", ["edge", "x"], "1 for each component of `x` at or above `edge`, and 0 elsewhere.",
            { "step(edge.\($0), x.\($0))" }
        ),
        (
            "smoothstep", "FloatingPoint", ["low", "high", "x"],
            "Each component of `x` mapped smoothly from the range from `low` to `high` onto 0 to 1.",
            { "smoothstep(low.\($0), high.\($0), x.\($0))" }
        ),
        (
            "fma", "FloatingPoint", ["e1", "e2", "e3"], "`e1 * e2 + e3` for each component, rounded once.",
            { "e3.\($0).addingProduct(e1.\($0), e2.\($0))" }
        ),
        (
            "mix", "FloatingPoint", ["e1", "e2", "e3"], "The linear blend of `e1` and `e2` by each component of `e3`.",
            { "mix(e1.\($0), e2.\($0), e3.\($0))" }
        ),
    ]
    for function in componentwise {
        source.line()
        source.line("/// \(function.documentation)")
        source.line("@inlinable")
        let parameters = function.parameters.map { "_ \($0): \(type)" }.joined(separator: ", ")
        source.block("public func \(function.name)<Scalar: \(function.constraint)>(\(parameters)) -> \(type)") {
            source.line("\(construct)(\(each(size, function.expression)))")
        }
    }

    source.line()
    source.line("/// The linear blend of `e1` and `e2` by `e3`.")
    source.line("@inlinable")
    source.block("public func mix<Scalar: FloatingPoint>(_ e1: \(type), _ e2: \(type), _ e3: Scalar) -> \(type)") {
        source.line("\(construct)(\(each(size) { "mix(e1.\($0), e2.\($0), e3)" }))")
    }

    source.line()
    source.line("// MARK: - Transcendental built-in functions")
    source.line("//")
    source.line("// These take any `Real` from swift-numerics, which Float, Double and Float16")
    source.line("// are. They apply to vectors only: Foundation and `Real` itself already have")
    source.line("// them for scalars.")

    // name, parameters, documentation and the expression for one component.
    let transcendental: [(String, [String], String, (String) -> String)] = [
        ("sin", ["e"], "The sine of each component, in radians.", { "Scalar.sin(e.\($0))" }),
        ("cos", ["e"], "The cosine of each component, in radians.", { "Scalar.cos(e.\($0))" }),
        ("tan", ["e"], "The tangent of each component, in radians.", { "Scalar.tan(e.\($0))" }),
        ("asin", ["e"], "The arcsine of each component, in radians.", { "Scalar.asin(e.\($0))" }),
        ("acos", ["e"], "The arccosine of each component, in radians.", { "Scalar.acos(e.\($0))" }),
        ("atan", ["e"], "The arctangent of each component, in radians.", { "Scalar.atan(e.\($0))" }),
        (
            "atan2", ["y", "x"], "The angle of each point (`x`, `y`) from the positive x axis, in radians.",
            { "Scalar.atan2(y: y.\($0), x: x.\($0))" }
        ),
        ("sinh", ["e"], "The hyperbolic sine of each component.", { "Scalar.sinh(e.\($0))" }),
        ("cosh", ["e"], "The hyperbolic cosine of each component.", { "Scalar.cosh(e.\($0))" }),
        ("tanh", ["e"], "The hyperbolic tangent of each component.", { "Scalar.tanh(e.\($0))" }),
        ("asinh", ["e"], "The inverse hyperbolic sine of each component.", { "Scalar.asinh(e.\($0))" }),
        ("acosh", ["e"], "The inverse hyperbolic cosine of each component.", { "Scalar.acosh(e.\($0))" }),
        ("atanh", ["e"], "The inverse hyperbolic tangent of each component.", { "Scalar.atanh(e.\($0))" }),
        ("exp", ["e"], "Euler's number raised to each component.", { "Scalar.exp(e.\($0))" }),
        ("exp2", ["e"], "2 raised to each component.", { "Scalar.exp2(e.\($0))" }),
        ("log", ["e"], "The natural logarithm of each component.", { "Scalar.log(e.\($0))" }),
        ("log2", ["e"], "The base-2 logarithm of each component.", { "Scalar.log2(e.\($0))" }),
        ("pow", ["e1", "e2"], "Each component of `e1` raised to that of `e2`.", { "Scalar.pow(e1.\($0), e2.\($0))" }),
    ]
    for (name, parameters, documentation, expression) in transcendental {
        source.line()
        source.line("/// \(documentation)")
        source.line("@inlinable")
        let list = parameters.map { "_ \($0): \(type)" }.joined(separator: ", ")
        source.block("public func \(name)<Scalar: Real>(\(list)) -> \(type)") {
            source.line("\(construct)(\(each(size, expression)))")
        }
    }

    source.line()
    source.line("// MARK: - Geometric built-in functions")
    source.line()
    source.line("/// The dot product of `e1` and `e2`.")
    source.line("@inlinable")
    source.block("public func dot<Scalar: Numeric>(_ e1: \(type), _ e2: \(type)) -> Scalar") {
        source.line("var result = e1.x * e2.x")
        for component in componentNames[1..<size] {
            source.line("result += e1.\(component) * e2.\(component)")
        }
        source.line("return result")
    }
    if size == 3 {
        source.line()
        source.line("/// The cross product of `e1` and `e2`.")
        source.line("@inlinable")
        source.block("public func cross<Scalar: SignedNumeric>(_ e1: \(type), _ e2: \(type)) -> \(type)") {
            source.line("let x: Scalar = e1.y * e2.z - e1.z * e2.y")
            source.line("let y: Scalar = e1.z * e2.x - e1.x * e2.z")
            source.line("let z: Scalar = e1.x * e2.y - e1.y * e2.x")
            source.line("return Vector3(x, y, z)")
        }
    }
    source.line()
    source.line("/// The length of `e`.")
    source.line("@inlinable")
    source.block("public func length<Scalar: FloatingPoint>(_ e: \(type)) -> Scalar") {
        source.line("dot(e, e).squareRoot()")
    }
    source.line()
    source.line("/// The distance between `e1` and `e2`.")
    source.line("@inlinable")
    source.block("public func distance<Scalar: FloatingPoint>(_ e1: \(type), _ e2: \(type)) -> Scalar") {
        source.line("length(e1 - e2)")
    }
    source.line()
    source.line("/// `e` scaled to a length of 1. The result is not finite when `e` is zero.")
    source.line("@inlinable")
    source.block("public func normalize<Scalar: FloatingPoint>(_ e: \(type)) -> \(type)") {
        source.line("e / length(e)")
    }
    source.line()
    source.line("/// `e1` if `e2` points away from `e3`, and `-e1` otherwise.")
    source.line("@inlinable")
    source.block(
        "public func faceForward<Scalar: FloatingPoint>(_ e1: \(type), _ e2: \(type), _ e3: \(type)) -> \(type)"
    ) {
        source.line("dot(e2, e3) < 0 ? e1 : -e1")
    }
    source.line()
    source.line("/// The reflection of the incident direction `e1` off a surface with normal `e2`.")
    source.line("@inlinable")
    source.block("public func reflect<Scalar: FloatingPoint>(_ e1: \(type), _ e2: \(type)) -> \(type)") {
        source.line("let scale: Scalar = 2 * dot(e2, e1)")
        source.line("return e1 - e2 * scale")
    }
    source.line()
    source.line("/// The refraction of the incident direction `e1` through a surface with normal")
    source.line("/// `e2`, for the ratio of indices of refraction `e3`. Zero on total internal")
    source.line("/// reflection.")
    source.line("@inlinable")
    source.block(
        "public func refract<Scalar: FloatingPoint>(_ e1: \(type), _ e2: \(type), _ e3: Scalar) -> \(type)"
    ) {
        source.line("let cosine: Scalar = dot(e2, e1)")
        source.line("let k: Scalar = 1 - e3 * e3 * (1 - cosine * cosine)")
        source.block("guard k >= 0 else") {
            source.line("return .zero")
        }
        source.line("let scale: Scalar = e3 * cosine + k.squareRoot()")
        source.line("return e1 * e3 - e2 * scale")
    }
}

func generateSwizzles(_ size: Int) -> String {
    let source = Source()
    source.line()
    source.line("// The components under the names WGSL gives them for colors, and swizzles:")
    source.line("// vectors of 2 to 4 components picked from this one in any order, read-only")
    source.line("// as in WGSL.")
    source.block("extension Vector\(size)") {
        for (color, component) in zip(colorNames, componentNames).prefix(size) {
            source.inlinable(
                "public var \(color): Scalar",
                "get { \(component) }", "set { \(component) = newValue }")
        }
        for names in [componentNames, colorNames] {
            let available = Array(names.prefix(size))
            source.line()
            for length in 2...4 {
                for sequence in sequences(of: available, length: length) {
                    let components = sequence.map { componentNames[available.firstIndex(of: $0)!] }
                    source.line(
                        "@inlinable public var \(sequence.joined()): \(vector(length)) { Vector\(length)(\(components.joined(separator: ", "))) }"
                    )
                }
            }
        }
    }
    return source.text
}

// MARK: - Matrices

func generateMatrix(columns: Int, rows: Int) -> String {
    let source = Source()
    let name = "Matrix\(columns)x\(rows)"
    let column = vector(rows)
    let row = vector(columns)
    let columnTuple = "(\(each(count: columns) { _ in column }))"
    let rowTuple = "(\(each(count: rows) { _ in row }))"
    let isSquare = columns == rows

    source.line()
    source.line("/// A matrix of \(columns) columns and \(rows) rows, stored as its columns in order with")
    source.line("/// no padding.")
    source.line("///")
    source.line("/// Its operators and the free functions on it follow WGSL's `mat\(columns)x\(rows)<T>`.")
    source.line("@frozen")
    source.block("public struct \(name)<Scalar>") {
        source.line("public var columns: \(columnTuple)")
        source.inlinable("public init(columns: \(columnTuple))", "self.columns = columns")
        source.line()
        source.line("/// A matrix with the given columns.")
        source.line("@inlinable")
        source.block("public init(\(each(count: columns) { "_ column\($0): \(column)" }))") {
            source.line("self.init(columns: (\(each(count: columns) { "column\($0)" })))")
        }
        source.line()
        source.line("/// A matrix with the given elements, column by column.")
        source.line("@inlinable")
        let elements = (0..<columns).flatMap { c in (0..<rows).map { r in "m\(c)\(r)" } }
        source.block("public init(\(elements.map { "_ \($0): Scalar" }.joined(separator: ", ")))") {
            source.line(
                "self.init(\(each(count: columns) { c in "\(column)(\(each(count: rows) { r in "m\(c)\(r)" }))" }))")
        }
        source.line()
        source.line("/// A matrix with the given rows.")
        source.line("@inlinable")
        source.block("public init(rows: \(rowTuple))") {
            source.line(
                "self.init(\(componentNames.prefix(columns).map { c in "\(column)(\(each(count: rows) { r in "rows.\(r).\(c)" }))" }.joined(separator: ", ")))"
            )
        }
        source.line()
        source.line("/// The number of columns.")
        source.line("@inlinable")
        source.line("public static var columnCount: Int { \(columns) }")
        source.line()
        source.line("/// The number of rows.")
        source.line("@inlinable")
        source.line("public static var rowCount: Int { \(rows) }")
        source.line()
        source.line("/// The column at `index`, counting from 0.")
        source.line("@inlinable")
        source.block("public subscript(index: Int) -> \(column)") {
            source.block("get") {
                source.switchBlock("index") {
                    for index in 0..<columns {
                        source.line("case \(index): return columns.\(index)")
                    }
                    source.line("default: preconditionFailure(\"Index out of range\")")
                }
            }
            source.block("set") {
                source.switchBlock("index") {
                    for index in 0..<columns {
                        source.line("case \(index): columns.\(index) = newValue")
                    }
                    source.line("default: preconditionFailure(\"Index out of range\")")
                }
            }
        }
        source.line()
        source.line("/// The element in column `column` and row `row`, counting from 0.")
        source.line("@inlinable")
        source.block("public subscript(column: Int, row: Int) -> Scalar") {
            source.line("get { self[column][row] }")
            source.line("set { self[column][row] = newValue }")
        }
    }

    // Conformances.
    source.line()
    source.line("extension \(name): Sendable where Scalar: Sendable {}")
    source.line()
    source.block("extension \(name): Equatable where Scalar: Equatable") {
        source.line("@inlinable")
        source.block("public static func == (lhs: Self, rhs: Self) -> Bool") {
            source.line(each(count: columns, separator: " && ") { "lhs.columns.\($0) == rhs.columns.\($0)" })
        }
    }
    source.line()
    source.block("extension \(name): Hashable where Scalar: Hashable") {
        source.line("@inlinable")
        source.block("public func hash(into hasher: inout Hasher)") {
            for index in 0..<columns {
                source.line("hasher.combine(columns.\(index))")
            }
        }
    }
    source.line()
    source.line("/// Encoded as an array of its columns.")
    source.block("extension \(name): Encodable where Scalar: Encodable") {
        source.line("@inlinable")
        source.block("public func encode(to encoder: any Encoder) throws") {
            source.line("var container = encoder.unkeyedContainer()")
            for index in 0..<columns {
                source.line("try container.encode(columns.\(index))")
            }
        }
    }
    source.line()
    source.block("extension \(name): Decodable where Scalar: Decodable") {
        source.line("@inlinable")
        source.block("public init(from decoder: any Decoder) throws") {
            source.line("var container = try decoder.unkeyedContainer()")
            for index in 0..<columns {
                source.line("let column\(index) = try container.decode(\(column).self)")
            }
            source.line("self.init(\(each(count: columns) { "column\($0)" }))")
        }
    }
    source.line()
    source.block("extension \(name): CustomStringConvertible") {
        source.block("public var description: String") {
            source.line("\"\(name)(\(each(count: columns) { "\\(columns.\($0))" }))\"")
        }
    }

    // Conversions.
    for (scalar, other) in [
        ("BinaryInteger", "BinaryInteger"), ("BinaryInteger", "BinaryFloatingPoint"),
        ("BinaryFloatingPoint", "BinaryInteger"), ("BinaryFloatingPoint", "BinaryFloatingPoint"),
    ] {
        source.line()
        source.block("extension \(name) where Scalar: \(scalar)") {
            source.line("/// Converts each element as `\(column)` converts its components.")
            source.line("@inlinable")
            source.block("public init<Other: \(other)>(_ other: \(matrix(columns, rows, "Other")))") {
                source.line("self.init(\(each(count: columns) { "\(column)(other.columns.\($0))" }))")
            }
        }
    }

    // Arithmetic.
    source.line()
    source.block("extension \(name): AdditiveArithmetic where Scalar: AdditiveArithmetic") {
        source.line("@inlinable")
        source.line("public static var zero: Self { Self(\(each(count: columns) { _ in ".zero" })) }")
        for operation in ["+", "-"] {
            source.inlinable(
                "public static func \(operation) (lhs: Self, rhs: Self) -> Self",
                "Self(\(each(count: columns) { "lhs.columns.\($0) \(operation) rhs.columns.\($0)" }))")
        }
    }
    source.line()
    source.block("extension \(name) where Scalar: SignedNumeric") {
        source.inlinable(
            "public static prefix func - (operand: Self) -> Self",
            "Self(\(each(count: columns) { "-operand.columns.\($0)" }))")
    }
    source.line()
    source.line("// Products of matrices and vectors are linear-algebra products, as in WGSL.")
    source.block("extension \(name) where Scalar: Numeric") {
        if isSquare {
            source.line()
            source.line("/// The matrix with ones on its diagonal and zeros elsewhere.")
            source.line("@inlinable")
            source.block("public static var identity: Self") {
                source.line(
                    "Self(\(each(count: columns) { c in "\(column)(\(each(count: rows) { r in r == c ? "1" : "0" }))" }))")
            }
        }
        source.inlinable(
            "public static func * (lhs: Self, rhs: Scalar) -> Self",
            "Self(\(each(count: columns) { "lhs.columns.\($0) * rhs" }))")
        source.inlinable(
            "public static func * (lhs: Scalar, rhs: Self) -> Self",
            "Self(\(each(count: columns) { "lhs * rhs.columns.\($0)" }))")
        source.inlinable("public static func *= (lhs: inout Self, rhs: Scalar)", "lhs = lhs * rhs")

        source.line()
        source.line("/// The product with the column vector `rhs`.")
        source.line("@inlinable")
        source.block("public static func * (lhs: Self, rhs: \(row)) -> \(column)") {
            source.line("var result = lhs.columns.0 * rhs.x")
            for index in 1..<columns {
                source.line("result += lhs.columns.\(index) * rhs.\(componentNames[index])")
            }
            source.line("return result")
        }
        source.line()
        source.line("/// The product of the row vector `lhs` with `rhs`.")
        source.line("@inlinable")
        source.block("public static func * (lhs: \(column), rhs: Self) -> \(row)") {
            source.line("\(row)(\(each(count: columns) { "dot(lhs, rhs.columns.\($0))" }))")
        }
        for resultColumns in sizes {
            source.line()
            source.line("/// The product with `rhs`, which applies `rhs` first when both are transforms.")
            source.line("@inlinable")
            source.block(
                "public static func * (lhs: Self, rhs: \(matrix(resultColumns, columns))) -> \(matrix(resultColumns, rows))"
            ) {
                source.line(
                    "\(matrix(resultColumns, rows))(\(each(count: resultColumns) { "lhs * rhs.columns.\($0)" }))")
            }
        }
        if isSquare {
            source.inlinable("public static func *= (lhs: inout Self, rhs: Self)", "lhs = lhs * rhs")
        }
    }

    // Functions.
    source.line()
    source.line("// MARK: - Matrix built-in functions")
    source.line()
    source.line("/// The matrix whose rows are the columns of `e`.")
    source.line("@inlinable")
    source.block("public func transpose<Scalar>(_ e: \(matrix(columns, rows))) -> \(matrix(rows, columns))") {
        source.line("\(matrix(rows, columns))(rows: e.columns)")
    }
    if isSquare {
        generateSquareMatrixFunctions(source, size: columns)
    }
    return source.text
}

func generateSquareMatrixFunctions(_ source: Source, size: Int) {
    let type = matrix(size, size)
    // a<row><column> names each element as it appears in the matrix.
    let elements = (0..<size).flatMap { row in
        (0..<size).map { column in "let a\(row)\(column): Scalar = e.columns.\(column).\(componentNames[row])" }
    }

    source.line()
    source.line("/// The determinant of `e`.")
    source.line("@inlinable")
    source.block("public func determinant<Scalar: SignedNumeric>(_ e: \(type)) -> Scalar") {
        switch size {
        case 2:
            source.line("e.columns.0.x * e.columns.1.y - e.columns.1.x * e.columns.0.y")
        case 3:
            source.line("dot(e.columns.0, cross(e.columns.1, e.columns.2))")
        default:
            elements.forEach(source.line)
            writeLaplaceExpansion(source)
            source.line("let positive: Scalar = s0 * c5 + s2 * c3 + s3 * c2 + s5 * c0")
            source.line("let negative: Scalar = s1 * c4 + s4 * c1")
            source.line("return positive - negative")
        }
    }

    source.line()
    source.line("/// The inverse of `e`. Its elements are not finite when `e` is singular.")
    source.line("///")
    source.line("/// WGSL has no such function; it is here because transforms need it.")
    source.line("@inlinable")
    source.block("public func inverse<Scalar: FloatingPoint>(_ e: \(type)) -> \(type)") {
        switch size {
        case 2:
            source.line("let scale: Scalar = 1 / determinant(e)")
            source.line("let adjugate = Matrix2x2(e.columns.1.y, -e.columns.0.y, -e.columns.1.x, e.columns.0.x)")
            source.line("return adjugate * scale")
        case 3:
            source.line("let (column0, column1, column2) = e.columns")
            source.line("let row0 = cross(column1, column2)")
            source.line("let scale: Scalar = 1 / dot(column0, row0)")
            source.line("let adjugate = Matrix3x3(rows: (row0, cross(column2, column0), cross(column0, column1)))")
            source.line("return adjugate * scale")
        default:
            elements.forEach(source.line)
            writeLaplaceExpansion(source)
            source.line("let positive: Scalar = s0 * c5 + s2 * c3 + s3 * c2 + s5 * c0")
            source.line("let negative: Scalar = s1 * c4 + s4 * c1")
            source.line("let scale: Scalar = 1 / (positive - negative)")
            // The adjugate, row by row.
            let adjugate = [
                ["a11 * c5 - a12 * c4 + a13 * c3", "-a01 * c5 + a02 * c4 - a03 * c3", "a31 * s5 - a32 * s4 + a33 * s3", "-a21 * s5 + a22 * s4 - a23 * s3"],
                ["-a10 * c5 + a12 * c2 - a13 * c1", "a00 * c5 - a02 * c2 + a03 * c1", "-a30 * s5 + a32 * s2 - a33 * s1", "a20 * s5 - a22 * s2 + a23 * s1"],
                ["a10 * c4 - a11 * c2 + a13 * c0", "-a00 * c4 + a01 * c2 - a03 * c0", "a30 * s4 - a31 * s2 + a33 * s0", "-a20 * s4 + a21 * s2 - a23 * s0"],
                ["-a10 * c3 + a11 * c1 - a12 * c0", "a00 * c3 - a01 * c1 + a02 * c0", "-a30 * s3 + a31 * s1 - a32 * s0", "a20 * s3 - a21 * s1 + a22 * s0"],
            ]
            for (row, terms) in adjugate.enumerated() {
                for (column, term) in terms.enumerated() {
                    source.line("let b\(row)\(column): Scalar = \(term)")
                }
            }
            source.line("let adjugate = Matrix4x4(")
            source.line("    rows: (")
            for row in 0..<4 {
                source.line("        Vector4(\(each(count: 4) { "b\(row)\($0)" }))\(row < 3 ? "," : "")")
            }
            source.line("    ))")
            source.line("return adjugate * scale")
        }
    }
}

/// The 2x2 minors of the top two rows (s) and the bottom two rows (c) of a 4x4
/// matrix, whose products sum to its determinant by the Laplace expansion.
func writeLaplaceExpansion(_ source: Source) {
    let pairs = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
    for (index, (i, j)) in pairs.enumerated() {
        source.line("let s\(index): Scalar = a0\(i) * a1\(j) - a1\(i) * a0\(j)")
    }
    for (index, (i, j)) in pairs.enumerated() {
        source.line("let c\(index): Scalar = a2\(i) * a3\(j) - a3\(i) * a2\(j)")
    }
}

