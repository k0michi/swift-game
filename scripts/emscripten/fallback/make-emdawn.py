#!/usr/bin/env python3
# Renames Emdawnwebgpu's wgpu* functions to emdawn_wgpu*, so that it can be linked next to
# dawn::native, and writes a DawnProcTable of them, for link-fallback.sh.
#
# Usage: make-emdawn.py <emdawnwebgpu_pkg> <output directory>
#
# Writes to the output directory:
#   rename.h           #defines wgpuX to emdawn_wgpuX, for compiling C and C++
#   js/*.js            the JS libraries with the same names changed
#   emdawn_procs.cpp   const DawnProcTable& EmdawnGetProcs(), compiled with rename.h and
#                      Dawn's dawn_proc_table.h
import os
import re
import sys

pkg, out = sys.argv[1:]
src = os.path.join(pkg, 'webgpu', 'src')
header = open(os.path.join(pkg, 'webgpu', 'include', 'webgpu', 'webgpu.h')).read()

# Every function the API declares: WGPU_EXPORT <type> wgpuX(...) WGPU_FUNCTION_ATTRIBUTE;
api = sorted(set(re.findall(r'\b(wgpu[A-Z]\w*)\s*\(', header)))

os.makedirs(os.path.join(out, 'js'), exist_ok=True)
with open(os.path.join(out, 'rename.h'), 'w') as f:
    f.write('// Generated by make-emdawn.py.\n#pragma once\n')
    for name in api:
        f.write(f'#define {name} emdawn_{name}\n')

# In the JS libraries, the names appear as definitions (wgpuX: ...), as dependencies and
# signatures (wgpuX__deps, wgpuX__sig, 'wgpuX') and as calls into C (_wgpuX). Only names of the
# API are changed, so that other identifiers starting with wgpu stay as they are.
api_set = set(api)
pattern = re.compile(r'(?<![A-Za-z0-9_$])(_?)(wgpu[A-Z]\w*?)(?=__|\b)')


def rename(match):
    underscore, name = match.groups()
    return f'{underscore}emdawn_{name}' if name in api_set else match.group(0)


renamed = {}
for library in ['library_webgpu_enum_tables.js', 'library_webgpu_generated_struct_info.js',
                'library_webgpu_generated_sig_info.js', 'library_webgpu.js']:
    text = open(os.path.join(src, library)).read()
    text, count = pattern.subn(rename, text)
    renamed[library] = count
    open(os.path.join(out, 'js', library), 'w').write(text)

# The table: field names are the function names without wgpu, starting lowercase.
with open(os.path.join(out, 'emdawn_procs.cpp'), 'w') as f:
    f.write('// Generated by make-emdawn.py. Compile with -include rename.h.\n')
    f.write('#include <algorithm>\n')
    f.write('#include <dawn/dawn_proc_table.h>\n')
    f.write('#include <dawn/dawn_version.h>\n\n')
    f.write('const DawnProcTable& EmdawnGetProcs() {\n')
    f.write('    static const DawnProcTable procs = [] {\n')
    f.write('        DawnProcTable p = {};\n')
    # dawnProcSetProcs checks that the table comes from the same Dawn.
    f.write('        std::ranges::copy(dawn::kDawnVersion, p.version);\n')
    for name in api:
        field = name[4].lower() + name[5:]
        f.write(f'        p.{field} = {name};\n')
    f.write('        return p;\n    }();\n    return procs;\n}\n')

print(f'{len(api)} functions;', ', '.join(f'{k}: {v} renamed' for k, v in renamed.items()))
